#!/usr/bin/env python3
"""Refinery what-if warm-start benchmark (synthetic data, linear models only).

ALL DATA IS SYNTHETIC (generated by refinery_stress.py in this folder; invented numbers, no operational data).
Question: after a planning change (crude supply cut, demand surge, spec change, price move), does starting the engine from the
previous optimal point (--warm-sol) cut iterations and time versus a cold solve, and is every returned solution still valid?

Protocol (labelled; NOT the 93-case gate): for each base case, solve cold -> base.sol. For each what-if, build the perturbed LP
(same columns, changed bounds / right-hand sides / costs), then solve it (a) cold and (b) warm with --warm-sol base.sol.
Every returned solution (cold and warm) is re-validated by an independent reader: rows, bounds and objective are re-evaluated from
the .sol, and HiGHS (reference only) gives status and objective. A row is "ok" only if the engine point is feasible (1e-6) and the
objective matches HiGHS within 1e-6 relative. Warm results that are optimal but differ from the oracle are WRONG and stop the run.
Report iterations (primary), wall time (secondary, host dependent), and whether the engine actually used the warm start
(stderr without "slack basis used"). Do not report speedups from rows where the warm start was not used.
Usage:
  python3 refinery_warmstart.py --engine ./taral --out ws_out [--bases base_lp_t6,base_lp_t12,base_lp_t24] [--method dual|primal]
Requires numpy and scipy (reference/checker only).
"""
import argparse, copy, csv, json, math, os, statistics, subprocess, sys, tempfile, time
import numpy as np
import refinery_stress as rs

SUP = [("SOUR", f) for f in (0.8, 0.5, 0.3, 0.0)] + [("SWEET", f) for f in (0.8, 0.5)]
DEM = (1.1, 1.2, 1.35)
SPEC = [(90.0, 0.20), (93.0, 0.12)]
COST = [(0.02, 11), (0.05, 12)]   # relative jitter on column costs, seed


def whatifs(base_sc):
    for cn, f in SUP:
        sc = dict(base_sc); sc["avail"] = {**base_sc.get("avail", {}), cn: f}
        yield f"supply_{cn}_{f}", sc, None
    for d in DEM:
        sc = dict(base_sc); sc["demand"] = d
        yield f"demand_{d}", sc, None
    for o, s in SPEC:
        sc = dict(base_sc); sc["oct_spec"], sc["sulf_spec"] = o, s
        yield f"spec_oct{o}_sulf{s}", sc, None
    for j, seed in COST:
        yield f"cost_jitter_{j}", dict(base_sc), (j, seed)


def jitter_costs(model, j, seed):
    cols, rows, coef = model
    rng = np.random.RandomState(seed)
    new = {}
    for c, (cost, lo, up, isint) in cols.items():
        f = 1.0 + j * (2 * rng.rand() - 1) if cost != 0 else 1.0
        new[c] = (cost * f, lo, up, isint)
    return new, rows, coef


def solve(engine, path, sol_out, warm=None, method=None, cap=100):
    js = sol_out + ".json"
    for p in (js, sol_out):
        if os.path.exists(p):
            os.remove(p)
    cmd = [engine, path, "--time-limit", str(cap), "--json", js, "--sol", sol_out]
    if method:
        cmd += ["--method", method]
    if warm:
        cmd += ["--warm-sol", warm]
    t = time.time()
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=cap * 3 + 60)
    wall = time.time() - t
    r = json.load(open(js)) if os.path.exists(js) else {"status": "no_json"}
    return r, (p.stderr or "") + (p.stdout or ""), wall


def validate(m, r, sol_path, hst, hobj):
    st = str(r.get("status", "")).lower()
    if st != "optimal":
        return ("noans:" + st), None
    vals = dict(l.split() for l in open(sol_path))
    x = np.array([float(vals[c]) for c in m["cols"]])
    v = rs.violation(m, x); obj = float(m["c"] @ x)
    if v > 1e-6:
        return "WRONG(viol %.2g)" % v, obj
    if hst != "optimal":
        return "WRONG(oracle %s)" % hst, obj
    if abs(obj - hobj) > 1e-6 * max(1, abs(hobj)):
        return "WRONG(obj %.9g vs %.9g)" % (obj, hobj), obj
    return "ok", obj


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", default="./taral"); ap.add_argument("--out", default="ws_out")
    ap.add_argument("--bases", default="base_lp_t6,base_lp_t12,base_lp_t24"); ap.add_argument("--method", default=None)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    scs = rs.scenarios()
    rows_out, wrong = [], 0
    for b in a.bases.split(","):
        base_sc = scs[b]
        bpath = os.path.join(a.out, b + ".mps"); bsol = os.path.join(a.out, b + ".base.sol")
        rs.write_mps(b, rs.build(base_sc), bpath)
        r0, _, w0 = solve(a.engine, bpath, bsol, method=a.method)
        if str(r0.get("status")).lower() != "optimal":
            print("base not optimal, skipping", b, r0.get("status")); continue
        print(f"BASE {b}: iterations {r0.get('iterations')} wall {w0:.2f}s obj {r0.get('objective')}", flush=True)
        for name, sc, jit in whatifs(base_sc):
            model = rs.build(sc)
            if jit:
                model = jitter_costs(model, *jit)
            path = os.path.join(a.out, f"{b}__{name}.mps")
            rs.write_mps(f"{b}_{name}", model, path)
            m = rs.parse_mps(path); hst, hobj = rs.highs(m)
            rc, ec, wc = solve(a.engine, path, path + ".cold.sol", method=a.method)
            rw, ew, ww = solve(a.engine, path, path + ".warm.sol", warm=bsol, method=a.method)
            vc, oc = validate(m, rc, path + ".cold.sol", hst, hobj)
            vw, ow = validate(m, rw, path + ".warm.sol", hst, hobj)
            used = "slack basis used" not in ew
            if vc.startswith("WRONG") or vw.startswith("WRONG"):
                wrong += 1
            row = dict(base=b, whatif=name, oracle=hst, oracle_obj=hobj, cold_status=rc.get("status"), cold_iters=rc.get("iterations"),
                       cold_wall=round(wc, 3), cold_check=vc, warm_status=rw.get("status"), warm_iters=rw.get("iterations"),
                       warm_wall=round(ww, 3), warm_check=vw, warm_used=used)
            rows_out.append(row)
            print(f"{b}/{name}: cold {row['cold_iters']} it ({vc}) warm {row['warm_iters']} it ({vw}) used={used}", flush=True)
            for f in (path, path + ".cold.sol", path + ".warm.sol", path + ".cold.sol.json", path + ".warm.sol.json"):
                if os.path.exists(f): os.remove(f)
    with open(os.path.join(a.out, "warmstart_table.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows_out[0].keys())); w.writeheader(); w.writerows(rows_out)
    ok = [r for r in rows_out if r["cold_check"] == "ok" and r["warm_check"] == "ok" and r["warm_used"]
          and r["cold_iters"] and r["warm_iters"] is not None]
    ratios = [r["warm_iters"] / r["cold_iters"] for r in ok]
    summ = dict(rows=len(rows_out), validated_both=len([r for r in rows_out if r["cold_check"] == "ok" and r["warm_check"] == "ok"]),
                warm_used=len([r for r in rows_out if r["warm_used"]]), wrong=wrong,
                median_iter_ratio_warm_over_cold=(statistics.median(ratios) if ratios else None),
                warm_worse=len([x for x in ratios if x > 1.0]), method=a.method or "default",
                note="synthetic data; iteration ratios only from rows where the warm start was used and both solves validated")
    json.dump(summ, open(os.path.join(a.out, "warmstart_summary.json"), "w"), indent=1)
    print(json.dumps(summ, indent=1))
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
